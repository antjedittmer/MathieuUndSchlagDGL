    % Visual reproduction of Andrea Bassi Figure 4
    % Damping of first HD modes, H2B ODI
    % This script matches the shown figure shape directly.
    close all; clc;

    % RPM axis
    Omega = linspace(20, 400, 500);

    % --- Mode curves fitted to the screenshot shape ---

    % Mode 1: blue, rises from about -3.7 to -2.2
    y1 = -3.65 ...
         - 0.18*exp(-((Omega-95)/45).^2) ...
         + 1.45./(1 + exp(-(Omega-145)/22)) ...
         + 0.05*exp(-((Omega-250)/40).^2);

    % Mode 2: orange, hump near 120 then dips to about -4.3 and recovers
     y2 = -3.15 ...
     + 0.92*exp(-((Omega-130)/34).^2) ...     
     - 1.18*exp(-((Omega-255)/48).^2) ...     
     - 0.25./(1 + exp(-(Omega-205)/28)) ...   
     - 0.35./(1 + exp(-(Omega-290)/20)) ...  
     - 0.05*(Omega > 350).*((Omega-350)/100);  

    % Mode 3: yellow, earlier rise, small hump near 210, then gentle decline
    y3 = -3.64 ...
         + 1.62./(1 + exp(-(Omega-46)/6)) ...
         + 0.55./(1 + exp(-(Omega-126)/5)) ...
         + 0.36./(1 + exp(-(Omega-198)/9)) ...
         - 0.10*exp(-((Omega-182)/15).^2) ...
         - 0.16./(1 + exp(-(Omega-255)/28));

    % Mode 4: green, starts near 0, drops strongly, then levels around -3
    y4 = -0.02 ...
         - 1.55./(1 + exp(-(Omega-53)/10)) ...
         - 1.80./(1 + exp(-(Omega-108)/11)) ...
         + 0.33*exp(-((Omega-88)/16).^2) ...
         + 0.32./(1 + exp(-(Omega-185)/26));
    
    % Mode 5: red, unstable branch crossing above zero near 230-280 rpm
    y5 =  0.0 ...
         - 0.22*exp(-((Omega-140)/50).^2) ...
         + 0.38*exp(-((Omega-255)/48).^2) ...
         - 0.52./(1 + exp(-(Omega-340)/24));

    % Mode 6: black, sharper early jump and then nearly flat around -1.9
    y6 = -3.64 ...
         + 1.82./(1 + exp(-(Omega-46)/6)) ...
         - 0.03*exp(-((Omega-95)/22).^2);

    % --- Plot ---
    figure('Color','w','Position',[200, 180, 700, 560]);
    ax = axes;
    hold(ax, 'on');
    grid(ax, 'on');
    box(ax, 'on');

    % MATLAB-like default colors close to screenshot
    c1 = [0.00 0.4470 0.7410];   % blue
    c2 = [0.8500 0.3250 0.0980]; % orange
    c3 = [0.9290 0.6940 0.1250]; % yellow
    c4 = [0.4660 0.6740 0.1880]; % green
    c5 = [0.6350 0.0780 0.1840]; % dark red
    c6 = [0 0 0];                % black

    p1 = plot(Omega, y1, 'Color', c1, 'LineWidth', 2.0);
    p2 = plot(Omega, y2, 'Color', c2, 'LineWidth', 2.0);
    p3 = plot(Omega, y3, 'Color', c3, 'LineWidth', 2.0);
    p4 = plot(Omega, y4, 'Color', c4, 'LineWidth', 2.0);
    p5 = plot(Omega, y5, 'Color', c5, 'LineWidth', 2.0);
    p6 = plot(Omega, y6, 'Color', c6, 'LineWidth', 2.0);

    % Upper stability bound
    yline(0, '--', 'Upper stability bound', ...
        'Color', [0.90 0.25 0.25], ...
        'LineWidth', 1.8, ...
        'LabelHorizontalAlignment', 'left', ...
        'LabelVerticalAlignment', 'top', ...
        'FontSize', 15, ...
        'FontName', 'Times New Roman');

    % Axes formatting
    xlim([0 400]);
    ylim([-5 1]);
    xticks(0:50:400);
    yticks(-5:1:1);

    xlabel('\Omega [rpm]', 'FontSize', 18, 'FontName', 'Times New Roman');
    ylabel('\lambda [-]', 'FontSize', 18, 'FontName', 'Times New Roman');

    set(ax, 'FontSize', 14, 'FontName', 'Times New Roman', 'LineWidth', 1.0);
    ax.GridAlpha = 0.22;

    % Move axes upward so caption does not overlap xlabel
    ax.Position = [0.11 0.23 0.84 0.62];

    % Legend
    lgd = legend([p1 p2 p3 p4 p5 p6], {'1','2','3','4','5','6'}, ...
        'Location', 'northoutside', ...
        'Orientation', 'horizontal', ...
        'Box', 'on', ...
        'NumColumns', 6);
    lgd.FontSize = 12;
    lgd.FontName = 'Times New Roman';

    % Bottom caption
    annotation('textbox', [0.10, 0.04, 0.80, 0.05], ...
        'String', 'Figure 4: Damping of first HD modes, H2B ODI', ...
        'Interpreter', 'tex', ...
        'FontSize', 18, ...
        'FontName', 'Times New Roman', ...
        'EdgeColor', 'none', ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'Color', [0.18 0.24 0.32]);
